function normalizeLanguage(value) {
  if (typeof value !== 'string') return null;
  const normalized = value.trim().toLowerCase();
  if (normalized === 'zh' || normalized === 'zh-cn' || normalized === 'zh_hans') return 'zh-CN';
  if (normalized === 'en' || normalized === 'en-us' || normalized === 'en-gb') return 'en';
  return null;
}

function format(value, variables) {
  if (!variables) return value;
  return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match
  );
}

function valueFor(entry, language) {
  if (!entry) return null;
  return entry[language === 'en' ? 1 : 0];
}

module.exports = function uiLanguage(req, res, next) {
  const requestedLanguage = normalizeLanguage(req.query && req.query.lang);
  const cookieLanguage = normalizeLanguage(req.cookies && req.cookies[COOKIE_NAME]);
  const language = requestedLanguage || cookieLanguage || DEFAULT_LANGUAGE;

  if (requestedLanguage && requestedLanguage !== cookieLanguage) {
    res.cookie(COOKIE_NAME, requestedLanguage, {
      httpOnly: false,
      maxAge: COOKIE_MAX_AGE,
      sameSite: 'lax'
    });
  }

  const translate = (key, variables) => format(valueFor(messages[key], language) || key, variables);
  const localizeError = message => valueFor(validationMessages[String(message)], language) || String(message);

  req.lang = language;
  req.t = translate;
  res.locals.lang = language;
  res.locals.t = translate;
  res.locals.localize_error = localizeError;
  const pagePath = (req.originalUrl || (req.baseUrl || '') + req.path).split('?')[0];
  res.locals.language_url = target => `${pagePath}?lang=${normalizeLanguage(target) || DEFAULT_LANGUAGE}`;
  next();
};

module.exports.messages = messages;
module.exports.normalizeLanguage = normalizeLanguage;
